"""From-scratch OCR: printed-text recognition trained with CTC.

No pretrained OCR, no pretrained vision-language weights. The encoder
(CNN) and decoder (BiLSTM) are randomly initialized and trained on
synthetic printed-text images generated by this module. PyTorch supplies
tensor operations, autodiff, and the CTC loss — not pretrained weights.

Stages (start small, verify each):
  1. Render synthetic printed-text images with a simple bitmap font.
  2. Train the CNN+BiLSTM+CTC model on them.
  3. Measure character accuracy on held-out images.
  4. Later: handwriting, tables, math notation.

The OCR output is not fed to the language model silently: the
read-image endpoint returns recognized text the student can correct,
and low-confidence regions are flagged.
"""

from __future__ import annotations

import numpy as np

