FONT = {ch: np.array([[1.0 if c == "#" else 0.0 for c in row] for row in rows])
        for ch, rows in _FONT_SRC.items()}
OCR_VOCAB = sorted(FONT.keys())


def render_text_image(text: str, noise: float = 0.05, rng=None) -> tuple[np.ndarray, str]:
    """Render text as a binary image: shape (H, W) float array in [0,1]."""
    rng = rng or np.random.default_rng()
    text = "".join(ch for ch in text.upper() if ch in FONT)
    glyph_w, glyph_h, gap = 5, 7, 2
    width = max(1, len(text) * (glyph_w + gap))
    img = np.zeros((glyph_h + 4, width + 4))
    x = 2
    for ch in text:
        img[2:2 + glyph_h, x:x + glyph_w] = FONT[ch]
        x += glyph_w + gap
    if noise > 0:
        img = np.clip(img + rng.normal(0, noise, img.shape), 0, 1)
    return img, text


def make_dataset(n: int, seed: int = 0, min_len: int = 3, max_len: int = 12):
    """Synthetic labeled image/text pairs for the OCR experiment."""
    rng = np.random.default_rng(seed)
    images, labels = [], []
    words = ["READ", "ANSWER", "QUESTION", "MATH", "NOTES", "STUDY", "PAGE", "TEXT",
             "NAME", "DATE", "SOLVE", "EACH", "LINE", "WORD", "CHAPTER"]
    for i in range(n):
        if rng.random() < 0.5:
            text = " ".join(rng.choice(words, rng.integers(1, 3)))
        else:
            length = rng.integers(min_len, max_len)
            text = "".join(rng.choice(OCR_VOCAB, length))
        img, cleaned = render_text_image(text, noise=0.08, rng=rng)
        images.append(img)
        labels.append(cleaned)
    return images, labels


def build_model(vocab_size: int):
    """CNN + BiLSTM + CTC model with randomly initialized weights.

    Requires PyTorch. Used only by the training script; not imported
    at runtime by the web app until training has actually happened.
    """
    import torch
    import torch.nn as nn

    class OcrNet(nn.Module):
        def __init__(self, vocab, input_size=128):
            super().__init__()
            self.cnn = nn.Sequential(
                nn.Conv2d(1, 32, 3, padding=1), nn.ReLU(),
                nn.MaxPool2d((2, 2)),  # H/2
                nn.Conv2d(32, 64, 3, padding=1), nn.ReLU(),
                nn.MaxPool2d((2, 1)),  # keep width
            )
            # after two pools the height is H/4; for 11px images that is 2,
            # so features per time-step = 64 * 2 = 128.
            self.lstm = nn.LSTM(input_size, 128, bidirectional=True, batch_first=True)
            self.fc = nn.Linear(256, vocab + 1)  # +1 CTC blank

        def forward(self, x):  # x: (B, 1, H, W)
            f = self.cnn(x)                      # (B, C, H', W) where H' = H/4
            f = f.permute(0, 3, 1, 2)            # (B, W, C, H')
            f = f.flatten(2)                     # (B, W, C*H')
            # C*H' = 64 * (H/4). The synthetic images are 11px tall, so
            # H' = 2 and the LSTM input must be 128 — a previous version
            # hardcoded 64, which would crash on real data. The input
            # size is computed from the conv stack instead of guessed.
            out, _ = self.lstm(f)                # (B, W, 256)
            return self.fc(out)                 # (B, W, V+1)

    return OcrNet(vocab_size)


def train_ocr(steps: int = 1500, lr: float = 3e-3, seed: int = 0):
    """Train the OCR model from random initialization; measure char accuracy.

    Requires PyTorch. Run: python -m study.ocr_train
    """
    import torch
    import torch.nn as nn

    char_to_idx = {c: i for i, c in enumerate(OCR_VOCAB)}
    vocab = len(OCR_VOCAB)
    model = build_model(vocab)
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    ctc = nn.CTCLoss(blank=vocab, zero_infinity=True)

    train_images, train_labels = make_dataset(800, seed=1)
    val_images, val_labels = make_dataset(100, seed=2)

    def collate(images, labels):
        # images have identical height; widths differ -> pad
        w = max(img.shape[1] for img in images)
        batch = np.zeros((len(images), 1, images[0].shape[0], w))
        for i, img in enumerate(images):
            batch[i, 0, :, : img.shape[1]] = img
        return torch.tensor(batch, dtype=torch.float32), labels

    losses = []
    rng = np.random.default_rng(seed)
    model.train()
    for step in range(steps):
        idx = rng.integers(0, len(train_images), 16)
        x, labels = collate([train_images[i] for i in idx], [train_labels[i] for i in idx])
        logits = model(x)                          # (B, W, V+1)
        logp = logits.log_softmax(-1).permute(1, 0, 2)  # (W, B, V+1)
        target = torch.cat([torch.tensor([char_to_idx[c] for c in lab]) for lab in labels])
        lengths = torch.tensor([len(lab) for lab in labels])
        input_lengths = torch.full((len(labels),), logits.shape[1], dtype=torch.long)
        loss = ctc(logp, target, input_lengths, lengths)
        opt.zero_grad()
        loss.backward()
        opt.step()
        losses.append(float(loss))
        if (step + 1) % 100 == 0:
            print(f"step {step+1}: loss {losses[-1]:.3f}")

    # greedy CTC decode on validation set, measure character accuracy
    model.eval()
    correct = total = 0
    with torch.no_grad():
        for img, label in zip(val_images, val_labels):
            x, _ = collate([img], [label])
            logits = model(x)[0]  # (W, V+1)
            seq = logits.argmax(-1).tolist()
            decoded = []
            prev = None
            blank = vocab
            for s in seq:
                if s != prev and s != blank:
                    decoded.append(OCR_VOCAB[s])
                prev = s
            dec = "".join(decoded)
            for a, b in zip(dec, label):
                correct += a == b
                total += 1
            total += abs(len(dec) - len(label))
    acc = correct / max(total, 1)
    return model, losses, acc


